"""Package demo metadata and canvas images for opening index.html via file://."""

import base64
import json
from pathlib import Path


def build_offline(demo_dir=None):
    demo_dir = Path(demo_dir) if demo_dir is not None else Path(__file__).resolve().parent / 'static' / 'demo'
    manifest = json.loads((demo_dir / 'manifest.json').read_text(encoding='utf-8'))
    images = {}
    # Ordinary <img> tags can read local files. Canvas export needs data URLs
    # so local file origins do not taint the canvas and block PNG downloads.
    for case in manifest['cases']:
        for k in range(case['nFg'] + 1):
            path = f"case_{case['id']}/layers/L{k}.webp"
            data = base64.b64encode((demo_dir / path).read_bytes()).decode('ascii')
            images[path] = 'data:image/webp;base64,' + data

    payload = json.dumps({'manifest': manifest, 'images': images}, ensure_ascii=True, separators=(',', ':'))
    output = demo_dir / 'offline.js'
    output.write_text(
        '// Generated by build_offline.py; do not edit by hand.\n'
        'window.CLD_OFFLINE = ' + payload + ';\n',
        encoding='utf-8',
    )
    print(f'Offline bundle: {len(images)} layers, {output.stat().st_size / 1e6:.2f} MB')


if __name__ == '__main__':
    build_offline()
